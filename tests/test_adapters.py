def test_every_registered_adapter_renders_without_io(source, v):
  canon = load_canonical(v, {}, source)
  for name, cls in REGISTRY.items():
    files = cls().render(canon)
    assert files and all(f.content for f in files), name
    assert cls().targets(canon) == [f.path for f in files]
