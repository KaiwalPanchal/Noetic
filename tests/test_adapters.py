def test_gemini_toml_roundtrips_awkward_bodies():
  for body in ["plain\n", "has ''' triple\nand \\ backslash\n", "ends with quote'", 'ends "dq"', 'x """ y\n', ""]:
    parsed = tomllib.loads(f"prompt = {toml_multiline(body)}\n")["prompt"]
    assert parsed == body


