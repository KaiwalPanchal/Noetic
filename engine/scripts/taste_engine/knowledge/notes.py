"""Knowledge layer: write notes into the vault.

Renders validated agent JSON into vault markdown.

Python, not the agent, writes every file. Each note gets the pipeline
frontmatter (status: pending_review + run id), so the human gate is always
visible in Obsidian.
"""

from __future__ import annotations

from pathlib import Path
import re

from taste_engine.knowledge.config import Config, slugify, today

STATUS_FLOW = ("pending_review", "approved", "published", "rejected")


def frontmatter(cfg: Config, agent: str, run_id: str, kind: str, extra: dict | None = None) -> str:
  lines = [
    "---",
    "author: ai-agent",
    f"agent: {cfg.agent} · pipeline/{agent}",
    f"created: {today()}",
    f"type: {kind}",
    "status: pending_review",
    f"run: {run_id}",
  ]
  for key, value in (extra or {}).items():
    lines.append(f"{key}: {value}")
  lines += [
    "---",
    f"> [!NOTE] Generated by the Taste Engine pipeline ({agent}) · run `{run_id}` · "
    f"**pending {cfg.owner}'s review**. Approve: `pipeline.py approve \"<this file>\"`.",
    "",
  ]
  return "\n".join(lines) + "\n"


def unique_path(path: Path) -> Path:
  """Never overwrite: foo.md → foo-2.md → foo-3.md."""
  if not path.exists():
    return path
  n = 2
  while (candidate := path.with_name(f"{path.stem}-{n}{path.suffix}")).exists():
    n += 1
  return candidate


def write(path: Path, text: str) -> Path:
  path = unique_path(path)
  path.parent.mkdir(parents=True, exist_ok=True)
  path.write_text(text, encoding="utf-8")
  return path


def bullets(items, empty="-") -> str:
  return "\n".join(f"- {i}" for i in items) if items else empty


def wikilink(cfg: Config, path_or_name: str) -> str:
  """Turn a vault path into [[wikilink]]; leave URLs alone."""
  if path_or_name.startswith("http"):
    return path_or_name
  rel = path_or_name.replace("\\", "/")
  if rel.endswith(".md"):
    rel = rel[:-3]
  return f"[[{rel}]]"


